const { DataTypes } = require('sequelize');
const sequelize = require('../config/database');

const User = sequelize.define('User', {
    username: {
        type: DataTypes.STRING,
        allowNull: false,
        unique: true
    },
    password: {
        type: DataTypes.STRING,
        allowNull: false
    },
    role: {
        type: DataTypes.STRING, // Changed to STRING to avoid ENUM issues in SQLite/Dev or updated ENUM
        defaultValue: 'customer'
    }
});

module.exports = User;
